def group_title(gname: str) -> str:
    """分组标题: 基础名 + 实际条目数(动态生成, 不会与内容失配)。"""
    base, _, _rest = gname.partition(' (')
    for g, feats in HOME_GROUPS:
        if g == gname or g.partition(' (')[0] == base:
            return f'{base} ({len(feats)} 项)'
    return base


def all_entries():
    """全部入口展平: [(功能名, 目标页名, 操作名)]"""
    out = []
    for _g, feats in HOME_GROUPS:
        out.extend(feats)
    out.extend(COMMON_ENTRIES)
    return out
